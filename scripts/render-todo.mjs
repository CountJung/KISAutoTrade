export function checkFreshness(source, html) {
  if (renderTodo(source) !== html) throw new Error('docs/todo.html이 원본과 다릅니다. npm run todo:render를 실행하세요.');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const source = readFileSync(sourcePath, 'utf8');
    if (process.argv.slice(2).some((argument) => argument !== '--check')) throw new Error('지원 인자: --check');
    if (process.argv.includes('--check')) checkFreshness(source, readFileSync(outputPath, 'utf8'));
    else writeFileSync(outputPath, renderTodo(source));
    console.log(`TODO ${process.argv.includes('--check') ? 'freshness PASS' : 'rendered'}: 열린 항목 ${parseTasks(source).length}개`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
