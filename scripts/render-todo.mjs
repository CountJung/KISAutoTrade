const escapeHtml = (value) => value.replace(/[&<>"']/g, (character) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[character]);

// Only local relative references and HTTPS links are meaningful in this document.
// Raw HTML and unsafe URL schemes are rendered as text, never executed.
function safeLink(value) {
  if (/^(?:https:\/\/|[a-zA-Z0-9_.#])/u.test(value)
      && !/^(?:[a-z][a-z0-9+.-]*:|\/\/)/iu.test(value.replace(/^https:\/\//u, ''))
      && !/[\s\\<>]/u.test(value)) return value;
  return null;
}

export function inlineMarkdown(value) {
  const tokens = [];
  const token = (html) => `\u0000${tokens.push(html) - 1}\u0000`;
  let escaped = escapeHtml(value.replace(/\u0000/g, ''));
  escaped = escaped.replace(/`([^`]+)`/g, (_, code) => token(`<code>${code}</code>`));
  escaped = escaped.replace(/\[([^\]\n]+)\]\(([^)\s]+)\)/g, (match, label, url) => {
    const href = safeLink(url);
    return href ? token(`<a href="${href}">${label}</a>`) : match;
  });
  escaped = escaped.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  return escaped.replace(/\u0000(\d+)\u0000/g, (_, index) => tokens[Number(index)]);
}

export function parseTasks(source) {
  const lines = source.split(/\r?\n/u);
  const tasks = [];
  let section = '할일';
  for (let index = 0; index < lines.length; index += 1) {
    const heading = lines[index].match(/^#{2,3}\s+(.*)$/u);
    if (heading) section = heading[1];
    const item = lines[index].match(/^- \[ \] (.*)$/u);
    if (!item) continue;
    const status = Object.entries(statuses).find(([, label]) => item[1].startsWith(`**${label}** `));
    if (!status) throw new Error(`docs/todo.md:${index + 1}: 열린 항목에 상태를 명시하세요.`);
    const body = [];
    let cursor = index + 1;
    while (cursor < lines.length && /^(?:\s{2,}.*|\s*)$/u.test(lines[cursor])) {
      body.push(lines[cursor]);
      cursor += 1;
    }
    const title = item[1].slice(status[1].length + 5);
    const id = title.match(/SOXQ-P\d-\d+/u)?.[0].toLowerCase()
      ?? `task-${createHash('sha256').update(title).digest('hex').slice(0, 10)}`;
    if (tasks.some((task) => task.id === id)) throw new Error(`중복 할일 ID: ${id}`);
    tasks.push({ id, section, status: status[0], title, body: body.filter((line) => line.trim()), line: index + 1 });
  }
  // Completion-history checklists and nested subcriteria are not independent open tasks.
  const openCount = lines.filter((line) => /^- \[ \] /u.test(line)).length;
  if (!tasks.length || tasks.length !== openCount) throw new Error('열린 항목 누락 또는 빈 목록입니다.');
  return tasks;
}

function bodyHtml(lines) {
  return lines.map((line) => {
    const checkbox = line.match(/^\s+- \[([ x])\] (.*)$/u);
    if (checkbox) return `<li class="subtask"><span aria-label="${checkbox[1] === 'x' ? '완료' : '미완료'}">${checkbox[1] === 'x' ? '☑' : '☐'}</span> ${inlineMarkdown(checkbox[2])}</li>`;
    return `<li>${inlineMarkdown(line.trim().replace(/^- /u, ''))}</li>`;
  }).join('\n');
}

