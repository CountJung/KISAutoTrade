import { expect, test, type Page } from '@playwright/test'
import { assertSimulationSafe, simulationNativeFixture } from './fixtures/simulationNativeFixture'

const acknowledgement = '선택 프로필의 인증된 KIS 시세 조회 요청을 승인합니다. 주문은 하지 않습니다.'
const preparation = (page: Page) => page.getByTestId('sector-data-preparation')
const scopeButton = (page: Page) => preparation(page).getByRole('button', { name: 'KIS 조회 범위 확인', exact: true })
const collectButton = (page: Page) => preparation(page).getByRole('button', { name: 'KIS 12종목 자료 수집', exact: true })
const ack = (page: Page) => preparation(page).getByRole('checkbox', { name: acknowledgement, exact: true })
const selectedScope = (page: Page) => preparation(page).getByText(/^선택 범위:/)

test('actual simulation router requires explicit scope and acknowledgment before native quote collection', async ({ page }) => {
  const state = await simulationNativeFixture(page)
  const calls = async (command: string) => (await state.snapshot()).calls.filter(call => call.command === command)
  await expect(page.getByRole('tab', { name: '자료 준비', exact: true })).toHaveAttribute('aria-selected', 'true')
  expect(await calls('get_sector_quote_scope')).toEqual([])
  expect(await calls('collect_sector_data')).toEqual([])
  await preparation(page).getByLabel('자료 준비 JSON', { exact: true }).fill(JSON.stringify(state.request))
  await expect(collectButton(page)).toBeDisabled()
  await scopeButton(page).click()
  await expect(selectedScope(page)).toContainText('프로필 A')
  await expect(collectButton(page)).toBeDisabled()
  expect(await calls('collect_sector_data')).toEqual([])
  await ack(page).check()
  await expect(collectButton(page)).toBeEnabled()
  await collectButton(page).click()
  await expect.poll(async () => (await calls('collect_sector_data')).length).toBe(1)
  expect((await calls('collect_sector_data'))[0].args).toEqual({ input: {
    expectedProfileId: 'A', authenticatedQuotesAcknowledged: true, manifest: state.request.bundle.manifest,
  } })
  await expect(ack(page)).not.toBeChecked()
  await expect(collectButton(page)).toBeDisabled()
  await assertSimulationSafe(state)
})

test('held scope response is discarded after actual profile mutation A to B to A', async ({ page }) => {
  const state = await simulationNativeFixture(page)
  await preparation(page).getByLabel('자료 준비 JSON', { exact: true }).fill(JSON.stringify(state.request))
  const before = await state.queryState()
  await state.configure('get_sector_quote_scope')
  await scopeButton(page).click()
  await expect.poll(async () => (await state.snapshot()).calls.filter(call => call.command === 'get_sector_quote_scope' && call.status === 'pending').length).toBe(1)
  await state.switchProfile('B')
  await expect(page.getByText('시세 조회 프로필: 합성 프로필 B', { exact: false })).toBeVisible()
  await state.switchProfile('A')
  await expect(page.getByText('시세 조회 프로필: 합성 프로필 A', { exact: false })).toBeVisible()
  const after = await state.queryState()
  expect(after.dataUpdateCount).toBeGreaterThan(before.dataUpdateCount)
  expect(after.dataUpdatedAt).toBe(before.dataUpdatedAt)
  await state.release('get_sector_quote_scope')
  await expect(scopeButton(page)).toBeEnabled()
  await expect(selectedScope(page)).toHaveCount(0)
  await expect(ack(page)).toBeDisabled()
  await expect(collectButton(page)).toBeDisabled()
  expect((await state.snapshot()).calls.filter(call => call.command === 'collect_sector_data')).toEqual([])
  expect((await state.snapshot()).calls.filter(call => call.command === 'set_active_profile').map(call => call.args)).toEqual([{ id: 'B' }, { id: 'A' }])
  // An explicit new lookup can authorize A again only after the stale response ended.
  await scopeButton(page).click()
  await expect(selectedScope(page)).toContainText('프로필 A')
  await expect(ack(page)).not.toBeChecked()
  await assertSimulationSafe(state)
})

test('same ID same timestamp publication discards held collection before React rerenders', async ({ page }) => {
  const state = await simulationNativeFixture(page)
  const text = JSON.stringify(state.request)
  await preparation(page).getByLabel('자료 준비 JSON', { exact: true }).fill(text)
  await scopeButton(page).click()
  await expect(selectedScope(page)).toContainText('프로필 A')
  await ack(page).check()
  await state.configure('collect_sector_data')
  await collectButton(page).click()
  await expect.poll(async () => (await state.snapshot()).calls.filter(call => call.command === 'collect_sector_data' && call.status === 'pending').length).toBe(1)
  const { before, after } = await state.republish('collect_sector_data')
  expect(after.profileId).toBe(before.profileId)
  expect(after.dataUpdatedAt).toBe(before.dataUpdatedAt)
  expect(after.dataUpdateCount).toBe(before.dataUpdateCount + 1)
  await expect(scopeButton(page)).toBeEnabled()
  await expect(selectedScope(page)).toHaveCount(0)
  await expect(ack(page)).not.toBeChecked()
  await expect(collectButton(page)).toBeDisabled()
  await expect(preparation(page).getByLabel('자료 준비 JSON', { exact: true })).toHaveValue(text)
  await expect(preparation(page)).not.toContainText('LATE_COLLECT_MUST_NOT_APPLY')
  expect((await state.snapshot()).calls.filter(call => call.command === 'collect_sector_data')).toHaveLength(1)
  await assertSimulationSafe(state)
})

test('profile changes preserve supplied USD input in flight replay results and manual paper draft', async ({ page }) => {
  const state = await simulationNativeFixture(page)
  const inputText = JSON.stringify(state.input)
  await page.getByRole('tab', { name: '세 전략 비교', exact: true }).click()
  await page.getByLabel('섹터 비교 자료 JSON', { exact: true }).fill(inputText)
  await state.configure('preview_sector_portfolio')
  await page.getByRole('button', { name: '세 전략 비교 계산', exact: true }).click()
  await expect.poll(async () => (await state.snapshot()).calls.filter(call => call.command === 'preview_sector_portfolio' && call.status === 'pending').length).toBe(1)
  await state.switchProfile('B')
  await state.release('preview_sector_portfolio')
  await expect(page.getByTestId('sector-portfolio-results')).toBeVisible()
  await expect(page.getByLabel('세 전략과 비교군 성과표', { exact: true })).toBeVisible()
  await expect(page.getByLabel('섹터 비교 자료 JSON', { exact: true })).toHaveValue(inputText)
  await page.getByRole('tab', { name: '모의 결과 대조', exact: true }).click()
  const draft = JSON.stringify({ initialCashUsd: 10_000, costBps: 10, startDate: state.input.evaluation[0].date,
    marks: [{ date: state.input.evaluation[0].date, strategy: 'base', equityUsd: 10_000, priceSource: '수동 보존 기록 · 합성 테스트' }] })
  await page.getByLabel('모의 원장 평가 JSON', { exact: true }).fill(draft)
  await state.switchProfile('A')
  await state.republish()
  await expect(page.getByLabel('모의 원장 평가 JSON', { exact: true })).toHaveValue(draft)
  await page.getByRole('tab', { name: '세 전략 비교', exact: true }).click()
  await expect(page.getByTestId('sector-portfolio-results')).toBeVisible()
  await expect(page.getByLabel('섹터 비교 자료 JSON', { exact: true })).toHaveValue(inputText)
  const snapshot = await state.snapshot()
  expect(snapshot.fakeBalanceUsd).toBe(99_999)
  const previews = snapshot.calls.filter(call => call.command === 'preview_sector_portfolio')
  expect(previews).toHaveLength(1)
  expect(previews[0].args).toEqual({ input: state.input })
  expect((previews[0].args.input as { initialCashUsd: number }).initialCashUsd).toBe(10_000)
  expect(JSON.stringify(previews[0].args)).not.toContain('99999')
  await assertSimulationSafe(state)
})
